    tail_rms_tracking_error,maximum_control_effort, ...
    final_tracking_error,final_Kx_estimation_error, ...
    final_Kr_estimation_error,final_Theta_estimation_error, ...
    max_V_increase);

fprintf('\nTask 1 validation passed.\n');
fprintf('  controllability rank: %d of %d\n', ...
    results.validation.controllability_rank,size(params.A,1));
fprintf('  maximum Re(lambda(Am)): %.3e\n', ...
    results.validation.reference_model_spectral_abscissa);
fprintf('  largest matching residual: %.3e\n\n',max([ ...
    results.validation.state_matching_residual, ...
    results.validation.command_matching_residual, ...
    results.validation.uncertainty_matching_residual]));
disp(task1_summary);


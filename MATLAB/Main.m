            task5_cases(2:end))), ...
        'Validate_Task5:StateAccessFailure', ...
        'Only the benchmark may use the true state for control.');
    assert(validation.observer_tail_improvement > 1, ...
        'Validate_Task5:NoObserverImprovement', ...
        'The selected LTR gain did not reduce observer error.');
    assert(validation.augmentation_improvement > 1, ...
        'Validate_Task5:NoAugmentationImprovement', ...
        'Adaptive augmentation did not improve tail tracking.');
    assert(augmented_case.maximum_augmentation_effort > 0, ...
        'Validate_Task5:InactiveAugmentation', ...
        'The adaptive augmentation never became active.');
    assert(all(maximum_state_norm < 2), ...
        'Validate_Task5:EmpiricalUnboundedness', ...
        'A Task-5 trajectory exceeded the conservative bound check.');
end

function evaluation = run_task6_evaluation(base_params)
% Run every controller against the same five scenarios.

    scenario_labels = {'Nominal','Constant disturbance', ...
        'Sinusoidal disturbance','Parameter step','Sensor noise'};
    controller_labels = {'Direct MRAC','Indirect MRAC', ...
        'Integral MRAC','Dead-zone MRAC','Sigma MRAC', ...
        'e-modification','Projection MRAC','LTR + augmentation'};

    previous_rng = rng;
    restore_rng = onCleanup(@() rng(previous_rng));
    rng(41,'twister');
    noise_std = [deg2rad(0.03)*ones(3,1);8e-4*ones(3,1)];
    noise_frequency = linspace(2,18,24);
    noise_cosine = randn(6,numel(noise_frequency));
    noise_sine = randn(6,numel(noise_frequency));

    n_scenarios = numel(scenario_labels);
    n_controllers = numel(controller_labels);
    scenario_results = repmat(struct('label','', ...
        'cases',{{}},'event_time',NaN, ...
        'parameter_step_time',NaN),1,n_scenarios);
    rms_tracking_error = zeros(n_scenarios,n_controllers);
    maximum_control_effort = zeros(n_scenarios,n_controllers);
    final_parameter_error = zeros(n_scenarios,n_controllers);

    for scenario_index = 1:n_scenarios
        scenario_params = configure_task6_scenario(base_params, ...
            scenario_index,noise_frequency,noise_cosine, ...
            noise_sine,noise_std);

        cases = cell(1,n_controllers);
        cases{1} = Direct_MRAC( ...
            scenario_params,'multisine','baseline');
        cases{2} = Indirect_MRAC(scenario_params,'multisine');
        cases{3} = Integral_MRAC( ...
            scenario_params,'multisine','integral');
        cases{4} = Direct_MRAC( ...
            scenario_params,'multisine','deadzone');
        cases{5} = Direct_MRAC( ...
            scenario_params,'multisine','sigma');
        cases{6} = Direct_MRAC( ...
            scenario_params,'multisine','emod');
        cases{7} = Direct_MRAC( ...
            scenario_params,'multisine','projection');
        cases{8} = OutputFeedback_MRAC( ...
            scenario_params,'multisine','augmented');

        for controller_index = 1:n_controllers
            case_result = cases{controller_index};
            metrics = [case_result.rms_tracking_error, ...
                case_result.maximum_control_effort, ...
                case_result.final_Theta_estimation_error];
            assert(all(isfinite(metrics)) ...
                && all(isfinite([case_result.x,case_result.e, ...
                    case_result.u]),'all'), ...
                'Task6:NonFiniteResult', ...
                'Task 6 produced a nonfinite result.');
            assert(case_result.t(end) >= 0.999*base_params.t_final, ...
                'Task6:IncompleteRun', ...
                'A Task 6 simulation ended before the requested time.');

            rms_tracking_error(scenario_index,controller_index) = ...
                metrics(1);
            maximum_control_effort(scenario_index,controller_index) = ...
                metrics(2);
            final_parameter_error(scenario_index,controller_index) = ...
                metrics(3);
        end

        scenario_results(scenario_index).label = ...
            scenario_labels{scenario_index};
        scenario_results(scenario_index).cases = cases;
        scenario_results(scenario_index).event_time = ...
            scenario_params.task6.event_time;
        if scenario_params.task6.parameter_step.enabled
            scenario_results(scenario_index).parameter_step_time = ...
                scenario_params.task6.parameter_step.time;
        end
    end

    scenario_name = repelem(string(scenario_labels(:)),n_controllers);
    controller_name = repmat(string(controller_labels(:)),n_scenarios,1);
    rms_column = reshape(rms_tracking_error.',[],1);
    effort_column = reshape(maximum_control_effort.',[],1);
    parameter_column = reshape(final_parameter_error.',[],1);

    evaluation = struct();
    evaluation.scenario_labels = scenario_labels;
    evaluation.controller_labels = controller_labels;
    evaluation.scenarios = scenario_results;
    evaluation.rms_tracking_error = rms_tracking_error;
    evaluation.maximum_control_effort = maximum_control_effort;
    evaluation.final_parameter_error = final_parameter_error;
    evaluation.summary = table(scenario_name,controller_name, ...
        rms_column,effort_column,parameter_column, ...
        'VariableNames',{'scenario','controller', ...
        'rms_tracking_error','maximum_control_effort', ...
        'final_Theta_estimation_error'});

    clear restore_rng;
end

function params = configure_task6_scenario( ...
        base_params,scenario_index,noise_frequency,noise_cosine, ...
        noise_sine,noise_std)
% Set the plant change, disturbance, and common sensor signal.

    params = base_params;
    params.disturbance.type = 'none';
    params.disturbance.start_time = 0;
    params.disturbance.constant = zeros(6,1);
    params.disturbance.amplitude = zeros(6,1);
    params.disturbance.frequency = zeros(6,1);

    params.task6.parameter_step.enabled = false;
    params.task6.parameter_step.time = 0.5*params.t_final;
    params.task6.parameter_step.Lambda_post = params.Lambda_true;
    params.task6.parameter_step.Theta_plant_T_post = ...
        params.Theta_plant_T;
    params.task6.event_time = NaN;
    params.task6.state_noise = @(t) zeros(6,1)+0*t;
    params.task6.output_noise = @(t) zeros(3,1)+0*t;

    disturbance_bound = 0;
    noise_bound = 0;
    switch scenario_index
        case 1
            params.task6.description = ...
                'No disturbance, nominal plant, exact initial parameters';

        case 2
            input_disturbance = [0.004;-0.003;0.004];
            params.disturbance.type = 'constant';
            params.disturbance.start_time = 0.2*params.t_final;
            params.task6.event_time = params.disturbance.start_time;
            params.disturbance.constant = params.B*input_disturbance;
            disturbance_bound = norm(params.disturbance.constant,2);
            params.task6.description = ...
                'Matched constant disturbance at the plant input';

        case 3
            input_amplitude = [0.004;0.003;0.0035];
            input_frequency = [0.37;0.61;0.83];
            input_phase = [0;0.7;1.3];
            params.disturbance.type = 'multisine';
            params.disturbance.start_time = 0.2*params.t_final;
            params.task6.event_time = params.disturbance.start_time;
            params.disturbance.amplitude = zeros(6,3);
            for input_index = 1:3
                params.disturbance.amplitude(:,input_index) = ...
                    params.B(:,input_index)*input_amplitude(input_index);
            end
            params.disturbance.frequency = repmat( ...
                input_frequency.',6,1);
            params.disturbance.phase = repmat(input_phase.',6,1);
            disturbance_bound = norm(sum( ...
                abs(params.disturbance.amplitude),2),2);
            params.task6.description = ...
                'Matched sinusoids with three unknown frequencies';

        case 4
            params.task6.parameter_step.enabled = true;
            params.task6.event_time = params.task6.parameter_step.time;
            params.task6.parameter_step.Lambda_post = [ ...
                0.82,0.03,0.00;
                0.03,0.90,0.02;
                0.00,0.02,0.78];
            params.task6.parameter_step.Theta_plant_T_post = ...
                1.18*params.Theta_plant_T;
            params.task6.description = ...
                'Step change in effectiveness and rotational uncertainty';

        case 5
            params.task6.state_noise = @(t) task6_gaussian_noise( ...
                t,noise_frequency,noise_cosine,noise_sine,noise_std);
            params.task6.output_noise = @(t) params.Cm ...
                *task6_gaussian_noise(t,noise_frequency, ...
                noise_cosine,noise_sine,noise_std);
            noise_bound = 3*norm(noise_std,2);
            params.task6.description = ...
                'Shared zero-mean band-limited Gaussian sensor noise';
    end

    params.task4.disturbance_bound = disturbance_bound;
    disturbance_threshold = 2*norm(params.P,2)*disturbance_bound ...
        /min(eig(params.Q));
    params.task4.deadzone_minimum = disturbance_threshold;
    params.task4.deadzone_epsilon = max(1e-5, ...
        1.10*disturbance_threshold+noise_bound);

    Lambda_post = params.task6.parameter_step.Lambda_post;
    Theta_post = params.task6.parameter_step.Theta_plant_T_post;
    Kx_post = (Lambda_post\ ...
        (params.G\[-params.Kp,-params.Kd])).';
    Kr_post = (Lambda_post\(params.G\params.Kp)).';
    Theta_star_post = (Lambda_post\Theta_post).';

    params.task4.projection.Kx_limit = ...
        max(abs(params.Kx_star),abs(Kx_post))+0.01;
    params.task4.projection.Kr_limit = ...
        max(abs(params.Kr_star),abs(Kr_post))+0.01;
    params.task4.projection.Theta_limit = ...
        max(abs(params.Theta_star),abs(Theta_star_post))+0.005;
    params.task4.projection.Kx_lower = ...
        -params.task4.projection.Kx_limit;
    params.task4.projection.Kx_upper = ...
        params.task4.projection.Kx_limit;
    params.task4.projection.Kr_lower = ...
        -params.task4.projection.Kr_limit;
    params.task4.projection.Kr_upper = ...
        params.task4.projection.Kr_limit;
    params.task4.projection.Theta_lower = ...
        -params.task4.projection.Theta_limit;
    params.task4.projection.Theta_upper = ...
        params.task4.projection.Theta_limit;
end

function noise = task6_gaussian_noise( ...
        t,frequency,cosine_coefficient,sine_coefficient,noise_std)
% Smooth band-limited Gaussian process shared by every controller.

    phase = frequency*t;
    noise = noise_std.*sum(cosine_coefficient.*cos(phase) ...
        +sine_coefficient.*sin(phase),2)/sqrt(numel(frequency));
end

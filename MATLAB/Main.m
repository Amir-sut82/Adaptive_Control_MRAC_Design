%% Physical plant
params = struct();

params.m     = 0.486;
params.g_acc = 9.81;

params.Ixx = 0.0043;
params.Iyy = 0.0142;
params.Izz = 0.0176;
params.Ixz = 0;                  % Product of inertia neglected
params.I = diag([params.Ixx,params.Iyy,params.Izz]);

params.dcg = 0.175;
params.hcg = 0.085;
params.b   = 3.13e-5;
params.d   = 1.2e-6;
params.d_over_b = params.d/params.b;

params.B_alloc = [0, 0,          params.dcg,      params.d_over_b;
                  0, params.hcg, 0,               0;
                  0, 0,          params.d_over_b, -params.dcg];

% The first allocation column is zero, so only u2, u3, and u4 are used.
params.active_channels = 2:4;
params.B_active = params.B_alloc(:,params.active_channels);
params.G = params.I\params.B_active;

%% Nonlinear plant model
% xdot = A*x + B*(Lambda*u + Theta_plant_T*Phi(x)) + eta(x,t)
params.A = [zeros(3),eye(3);
            zeros(3),zeros(3)];
params.B = [zeros(3);
            params.G];

% Rotational coefficients for the diagonal-inertia model.
params.a_p = (params.Iyy-params.Izz)/params.Ixx;
params.a_q = (params.Izz-params.Ixx)/params.Iyy;
params.a_r = (params.Ixx-params.Iyy)/params.Izz;
params.c_d = 0.01;

params.H_true = [params.a_p,0,          0,          -params.c_d,0,          0;
                 0,         params.a_q,0,           0,         -params.c_d,0;
                 0,         0,         params.a_r,  0,          0,         -params.c_d];

% B=[0;G], so Theta_plant_T=G\H_true in the project model.
params.Theta_plant_T = params.G\params.H_true;

% This plant value remains hidden from the adaptive controller.
params.Lambda_true = eye(3);     % Nominal Task-1 effectiveness

% Task 1 is disturbance-free.
params.disturbance.type      = 'none';
params.disturbance.start_time = 0;
params.disturbance.constant  = zeros(6,1);
params.disturbance.amplitude = zeros(6,1);
params.disturbance.frequency = zeros(6,1);

%% Reference model
params.Kp = 4*eye(3);
params.Kd = 4*eye(3);
[params.Am,params.Bm,params.Cm] = Reference_Model(params);

% Ideal gains are used only for validation and plot reference lines.
params.Kx_star_T = params.Lambda_true\ ...
    (params.G\[-params.Kp,-params.Kd]);
params.Kr_star_T = params.Lambda_true\ ...
    (params.G\params.Kp);

% The minus sign in the control law gives
% Lambda*Theta_star_T=Theta_plant_T at exact matching.
params.Theta_star_T = params.Lambda_true\params.Theta_plant_T;

params.Kx_star    = params.Kx_star_T.';
params.Kr_star    = params.Kr_star_T.';
params.Theta_star = params.Theta_star_T.';

%% Lyapunov matrix
params.Q = eye(6);
params.P = lyap(params.Am',params.Q);

%% Adaptation gains
params.Gamma_x     = 50*eye(6);
params.Gamma_r     = 50*eye(3);
params.Gamma_theta = 50*eye(6);

%% Initial conditions
params.x0  = zeros(6,1);
params.xm0 = zeros(6,1);

params.Kx_hat0    = zeros(6,3);
params.Kr_hat0    = zeros(3,3);
params.Theta_hat0 = zeros(6,3);

%% Step and multisine commands
params.command.start_time = 1;
params.command.step_value = deg2rad([5;-5;8]);

% Five tones per axis improve PE without changing the command scale.
params.command.multisine_peak = deg2rad([10;10;15]);
params.command.multisine_weights = [0.30,0.24,0.19,0.15,0.12];
params.command.multisine_amplitude = ...
    params.command.multisine_peak.* ...
    params.command.multisine_weights;
params.command.multisine_frequency = [ ...
    0.31,0.53,0.79,1.07,1.37;
    0.37,0.61,0.89,1.19,1.43;
    0.43,0.67,0.97,1.27,1.51];
params.command.multisine_phase = zeros(3,5);

%% Simulation settings
params.t_final = 60;
params.ode_opts = odeset('RelTol',1e-7, ...
                         'AbsTol',1e-9, ...
                         'MaxStep',0.01);

%% Task 1 simulations
step_results = Direct_MRAC(params,'step');
multisine_results = Direct_MRAC(params,'multisine');

results = struct();
results.task1 = [step_results,multisine_results];
% Plot_Results writes image files only.
results.output_dir = fullfile(project_root,'Results');

if ~exist(results.output_dir,'dir')
    mkdir(results.output_dir);
end


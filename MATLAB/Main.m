    abs(task4_params.Kx_star)+0.002;
task4_params.task4.projection.Kr_limit = ...
    abs(task4_params.Kr_star)+0.002;
task4_params.task4.projection.Theta_limit = ...
    abs(task4_params.Theta_star)+0.001;
task4_params.task4.projection.Kx_lower = ...
    -task4_params.task4.projection.Kx_limit;
task4_params.task4.projection.Kx_upper = ...
    task4_params.task4.projection.Kx_limit;
task4_params.task4.projection.Kr_lower = ...
    -task4_params.task4.projection.Kr_limit;
task4_params.task4.projection.Kr_upper = ...
    task4_params.task4.projection.Kr_limit;
task4_params.task4.projection.Theta_lower = ...
    -task4_params.task4.projection.Theta_limit;
task4_params.task4.projection.Theta_upper = ...
    task4_params.task4.projection.Theta_limit;

task4_method_names = { ...
    'baseline','deadzone','sigma','emod','projection'};
task4_cases = cell(size(task4_method_names));
for method_index = 1:numel(task4_method_names)

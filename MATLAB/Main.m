function validation = Validate_Task4(params,task4_cases)
%VALIDATE_TASK4 Internal UUB and projection-set consistency checks.

    if numel(task4_cases) ~= 5
        error('Validate_Task4:CaseCount', ...
            'Expected baseline and four robust Task-4 simulations.');
    end

    method_names = cellfun(@(item) item.robust_method, ...
        task4_cases,'UniformOutput',false);
    required_methods = {'baseline','deadzone','sigma', ...
        'emod','projection'};
    assert(isequal(method_names,required_methods), ...
        'Validate_Task4:MethodOrder', ...
        'The required robust methods are incomplete or out of order.');

    validation = struct();
    validation.disturbance_bound = ...
        params.task4.disturbance_bound;
    validation.deadzone_minimum = ...
        params.task4.deadzone_minimum;
    validation.deadzone_threshold = ...
        params.task4.deadzone_epsilon;

    actual_disturbance_norm = zeros(numel(task4_cases),1);
    maximum_state_norm = zeros(numel(task4_cases),1);
    for case_index = 1:numel(task4_cases)
        case_result = task4_cases{case_index};
        assert(all(isfinite([case_result.x,case_result.e, ...
            case_result.u,case_result.parameter_error_norm]),'all'), ...
            'Validate_Task4:NonFiniteTrajectory', ...
            'A Task-4 method produced a nonfinite trajectory.');
        actual_disturbance_norm(case_index) = max( ...
            vecnorm(case_result.eta,2,2));
        maximum_state_norm(case_index) = max( ...
            vecnorm(case_result.x,2,2));
    end
    validation.actual_maximum_disturbance = ...
        max(actual_disturbance_norm);
    validation.maximum_state_norm = maximum_state_norm;

    projection_case = task4_cases{ ...
        strcmp(method_names,'projection')};
    projection_bounds = params.task4.projection;
    Kx_upper = reshape(projection_bounds.Kx_upper,1,6,3);
    Kx_lower = reshape(projection_bounds.Kx_lower,1,6,3);
    Kr_upper = reshape(projection_bounds.Kr_upper,1,3,3);
    Kr_lower = reshape(projection_bounds.Kr_lower,1,3,3);
    Theta_upper = reshape(projection_bounds.Theta_upper,1,6,3);
    Theta_lower = reshape(projection_bounds.Theta_lower,1,6,3);
    projection_violations = [ ...
        max(projection_case.Kx_hat-Kx_upper,[],'all'), ...
        max(Kx_lower-projection_case.Kx_hat,[],'all'), ...
        max(projection_case.Kr_hat-Kr_upper,[],'all'), ...
        max(Kr_lower-projection_case.Kr_hat,[],'all'), ...
        max(projection_case.Theta_hat-Theta_upper,[],'all'), ...
        max(Theta_lower-projection_case.Theta_hat,[],'all')];
    validation.projection_max_violation = ...
        max([0,projection_violations]);

    validation.ideal_set_margin = min([ ...
        min(params.Kx_star-projection_bounds.Kx_lower,[],'all'), ...
        min(projection_bounds.Kx_upper-params.Kx_star,[],'all'), ...
        min(params.Kr_star-projection_bounds.Kr_lower,[],'all'), ...
        min(projection_bounds.Kr_upper-params.Kr_star,[],'all'), ...
        min(params.Theta_star-projection_bounds.Theta_lower,[],'all'), ...
        min(projection_bounds.Theta_upper-params.Theta_star,[],'all')]);
    validation.baseline_parameter_excursion = ...
        task4_cases{1}.parameter_excursion_from_initial;

    assert(validation.disturbance_bound > 0 ...
        && validation.actual_maximum_disturbance ...
        <= validation.disturbance_bound*(1+1e-10), ...
        'Validate_Task4:DisturbanceBoundFailure', ...
        'The configured analytical disturbance bound is invalid.');
    assert(validation.deadzone_threshold ...
        >= validation.deadzone_minimum, ...
        'Validate_Task4:DeadzoneTooSmall', ...
        'The dead-zone threshold does not satisfy the UUB bound.');
    assert(params.task4.sigma > 0 && params.task4.sigma_e > 0, ...
        'Validate_Task4:InvalidLeakage', ...
        'Both leakage coefficients must be positive.');
    assert(validation.ideal_set_margin > 0, ...
        'Validate_Task4:IdealOutsideProjectionSet', ...
        'The projection set must contain the ideal parameters.');
    assert(validation.projection_max_violation < 1e-5, ...
        'Validate_Task4:ProjectionViolation', ...
        'The projection trajectory left its admissible convex set.');
    assert(validation.baseline_parameter_excursion > 1e-6, ...
        'Validate_Task4:NoBaselineDrift', ...
        'The bounded disturbance did not produce observable parameter drift.');
    assert(all(maximum_state_norm < 1), ...
        'Validate_Task4:EmpiricalUnboundedness', ...
        'A Task-4 state trajectory exceeded the conservative UUB check.');
end

function validation = Validate_Task5(params,task5_cases,design)

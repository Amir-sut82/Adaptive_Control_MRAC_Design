case_label = string({results.task1.label}).';
rms_tracking_error = [results.task1.rms_tracking_error].';
maximum_control_effort = [results.task1.maximum_control_effort].';
final_tracking_error = [results.task1.final_tracking_error].';
final_Kx_estimation_error = ...
    [results.task1.final_Kx_estimation_error].';
final_Kr_estimation_error = ...
    [results.task1.final_Kr_estimation_error].';
final_Theta_estimation_error = ...
    [results.task1.final_Theta_estimation_error].';
tail_rms_tracking_error = ...
    [results.validation.cases.tail_rms_tracking_error].';
max_V_increase = [results.validation.cases.max_V_increase].';


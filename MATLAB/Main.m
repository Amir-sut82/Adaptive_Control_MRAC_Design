%% Task 4: robust modifications under one bounded disturbance
task4_params = params;
task4_params.t_final = 120;
task4_params.ode_opts = odeset('RelTol',1e-7, ...
    'AbsTol',1e-9,'MaxStep',0.02);

% Starting at the matching gains isolates disturbance-driven parameter drift.
% Only the projection method receives the prior bounds defined below.
task4_params.Kx_hat0 = task4_params.Kx_star;
task4_params.Kr_hat0 = task4_params.Kr_star;
task4_params.Theta_hat0 = task4_params.Theta_star;

% Every method sees the same bounded, three-tone disturbance.
task4_params.disturbance.type = 'multisine';
task4_params.disturbance.start_time = 0;
task4_params.disturbance.amplitude = [ ...
    3.0e-4,2.0e-4,1.0e-4;
    2.5e-4,2.0e-4,1.5e-4;
    2.8e-4,1.8e-4,1.2e-4;
    3.0e-3,2.0e-3,1.0e-3;
    2.8e-3,1.8e-3,1.2e-3;
    3.2e-3,2.1e-3,1.1e-3];
task4_params.disturbance.frequency = [ ...
    0.17,0.43,0.79;
    0.23,0.53,0.91;
    0.29,0.61,1.03;
    0.19,0.47,0.83;
    0.31,0.67,1.09;
    0.37,0.73,1.19];
task4_params.disturbance.phase = [ ...
    0.0,0.4,0.8;
    0.2,0.6,1.0;
    0.4,0.8,1.2;
    0.6,1.0,1.4;
    0.8,1.2,1.6;
    1.0,1.4,1.8];

% Triangle-inequality bound on ||eta(t)||_2.
task4_params.task4.disturbance_bound = norm( ...
    sum(abs(task4_params.disturbance.amplitude),2),2);
task4_params.task4.deadzone_minimum = ...
    2*norm(task4_params.P,2) ...
    *task4_params.task4.disturbance_bound ...
    /min(eig(task4_params.Q));

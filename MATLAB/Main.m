function validation = Validate_Task1(params,task1)
%VALIDATE_TASK1 Internal consistency checks for the Task-1 simulation.

    if numel(task1) ~= 2
        error('Validate_Task1:CaseCount', ...
            'Expected the step and multisine Task-1 simulations.');
    end

    validation = struct();
    validation.reference_model_spectral_abscissa = ...
        max(real(eig(params.Am)));
    validation.controllability_rank = rank(ctrb(params.A,params.B));
    validation.input_effectiveness_min_eigenvalue = ...
        min(eig((params.Lambda_true+params.Lambda_true.')/2));
    validation.lyapunov_P_min_eigenvalue = ...
        min(eig((params.P+params.P.')/2));
    validation.state_matching_residual = norm( ...
        params.A+params.B*params.Lambda_true*params.Kx_star_T ...
        -params.Am,'fro');
    validation.command_matching_residual = norm( ...
        params.B*params.Lambda_true*params.Kr_star_T ...
        -params.Bm,'fro');
    validation.uncertainty_matching_residual = norm( ...
        params.Lambda_true*params.Theta_star_T ...
        -params.Theta_plant_T,'fro');
    validation.lyapunov_equation_residual = norm( ...
        params.Am.'*params.P+params.P*params.Am+params.Q,'fro');

    assert(validation.reference_model_spectral_abscissa < 0, ...
        'Validate_Task1:UnstableReferenceModel','Am must be Hurwitz.');
    assert(validation.controllability_rank == size(params.A,1), ...
        'Validate_Task1:UncontrollablePlant', ...
        'The pair (A,B) must be controllable.');
    assert(norm(params.Lambda_true-params.Lambda_true.','fro') < 1e-12 ...
        && validation.input_effectiveness_min_eigenvalue > 0, ...
        'Validate_Task1:InvalidInputEffectiveness', ...
        ['The implemented Lyapunov proof requires Lambda_true to be ' ...
         'symmetric positive definite.']);
    assert(validation.lyapunov_P_min_eigenvalue > 0, ...
        'Validate_Task1:InvalidLyapunovMatrix', ...
        'The Lyapunov solution P must be positive definite.');

    algebra_tolerance = 1e-9;
    assert(validation.state_matching_residual < algebra_tolerance, ...
        'Validate_Task1:StateMatchingFailure', ...
        'The state-feedback matching equation is not satisfied.');
    assert(validation.command_matching_residual < algebra_tolerance, ...
        'Validate_Task1:CommandMatchingFailure', ...
        'The command matching equation is not satisfied.');
    assert(validation.uncertainty_matching_residual < algebra_tolerance, ...
        'Validate_Task1:UncertaintyMatchingFailure', ...
        'The uncertainty cancellation matching equation is not satisfied.');
    assert(validation.lyapunov_equation_residual < algebra_tolerance, ...
        'Validate_Task1:LyapunovEquationFailure', ...
        'P does not satisfy the requested Lyapunov equation.');

    validation.cases = repmat(struct( ...
        'label','', ...
        'max_V_increase',NaN, ...
        'tail_rms_tracking_error',NaN, ...
        'maximum_absolute_state',NaN, ...
        'all_values_finite',false),1,numel(task1));

    for ic = 1:numel(task1)
        case_result = task1(ic);
        error_norm_squared = sum(case_result.e.^2,2);
        tail_start = max(1,floor(0.8*numel(case_result.t)));
        tail_time = case_result.t(tail_start:end);
        tail_error = error_norm_squared(tail_start:end);

        case_validation = struct();
        case_validation.label = case_result.label;
        case_validation.max_V_increase = max(diff(case_result.V));
        case_validation.tail_rms_tracking_error = sqrt( ...
            trapz(tail_time,tail_error)/(tail_time(end)-tail_time(1)));
        case_validation.maximum_absolute_state = ...
            max(abs(case_result.x),[],'all');
        case_validation.all_values_finite = ...
            all(isfinite([case_result.x,case_result.xm, ...
                case_result.e,case_result.u]),'all');

        V_tolerance = 1e-10*max(1,abs(case_result.V(1)));
        assert(case_validation.all_values_finite, ...
            'Validate_Task1:NonFiniteTrajectory', ...
            '%s produced a nonfinite trajectory.',case_result.label);
        assert(case_validation.max_V_increase <= V_tolerance, ...
            'Validate_Task1:LyapunovIncrease', ...
            '%s violates the nonincreasing Lyapunov check.', ...
            case_result.label);
        validation.cases(ic) = case_validation;
    end
end

function validation = Validate_Task2(params,direct_results,indirect_results)
%VALIDATE_TASK2 Internal consistency checks for the Task-2 comparison.

    if numel(direct_results) ~= 2 || numel(indirect_results) ~= 2
        error('Validate_Task2:CaseCount', ...
            'Expected step and multisine results for both controllers.');
    end

    symmetric_lambda = ...
        (params.Lambda_true+params.Lambda_true.')/2;
    validation = struct();
    validation.lambda_symmetry_residual = norm( ...
        params.Lambda_true-params.Lambda_true.','fro');
    validation.lambda_min_eigenvalue = min(eig(symmetric_lambda));
    validation.lambda_condition_number = cond(params.Lambda_true);
    validation.identifier_lyapunov_residual = norm( ...
        (-params.indirect.L_id).'*params.indirect.P_id ...
        + params.indirect.P_id*(-params.indirect.L_id) ...
        + params.indirect.Q_id,'fro');
    validation.state_matching_residual = norm( ...
        params.A+params.B*params.Lambda_true*params.Kx_star_T ...
        -params.Am,'fro');
    validation.command_matching_residual = norm( ...
        params.B*params.Lambda_true*params.Kr_star_T ...
        -params.Bm,'fro');
    validation.uncertainty_matching_residual = norm( ...
        params.Lambda_true*params.Theta_star_T ...
        -params.Theta_plant_T,'fro');

    assert(validation.lambda_symmetry_residual < 1e-12 ...
        && validation.lambda_min_eigenvalue > 0, ...
        'Validate_Task2:InvalidLambda', ...
        'The comparison Lambda_true must be symmetric positive definite.');
    assert(validation.identifier_lyapunov_residual < 1e-9, ...
        'Validate_Task2:IdentifierLyapunovFailure', ...
        'P_id does not solve the identifier Lyapunov equation.');
    assert(max([validation.state_matching_residual, ...
        validation.command_matching_residual, ...
        validation.uncertainty_matching_residual]) < 1e-9, ...
        'Validate_Task2:MatchingFailure', ...
        'The Task-2 ideal matching equations are not satisfied.');

    validation.cases = repmat(struct( ...
        'label','', ...
        'direct_rms_tracking_error',NaN, ...
        'indirect_rms_tracking_error',NaN, ...
        'indirect_final_prediction_error',NaN, ...
        'information_effective_rank',NaN, ...
        'minimum_regularized_singular_value',NaN), ...
        1,numel(indirect_results));

    for ic = 1:numel(indirect_results)
        direct_case = direct_results(ic);
        indirect_case = indirect_results(ic);

        assert(strcmp(direct_case.command_type, ...
            indirect_case.command_type), ...
            'Validate_Task2:CommandMismatch', ...
            'Direct and indirect result arrays are not aligned.');
        assert(all(isfinite([direct_case.x,direct_case.xm, ...
            direct_case.e,direct_case.u]),'all'), ...
            'Validate_Task2:NonFiniteDirectTrajectory', ...
            '%s produced a nonfinite direct-MRAC trajectory.', ...
            direct_case.label);
        assert(all(isfinite([indirect_case.x,indirect_case.xm, ...
            indirect_case.x_predictor,indirect_case.e, ...
            indirect_case.u]),'all'), ...
            'Validate_Task2:NonFiniteIndirectTrajectory', ...
            '%s produced a nonfinite indirect-MRAC trajectory.', ...
            indirect_case.label);
        assert(indirect_case.t(end) >= ...
            params.t_final*(1-10*eps), ...
            'Validate_Task2:IncompleteSimulation', ...
            '%s did not reach the requested final time.', ...
            indirect_case.label);

        minimum_regularized_singular_value = min( ...
            indirect_case.minimum_used_singular_value);
        assert(minimum_regularized_singular_value >= ...
            params.indirect.lambda_singular_value_floor*(1-1e-12), ...
            'Validate_Task2:UnsafeInverse', ...
            'The certainty-equivalence inverse violated its singular-value floor.');

        case_validation = struct();
        case_validation.label = indirect_case.label;
        case_validation.direct_rms_tracking_error = ...
            direct_case.rms_tracking_error;
        case_validation.indirect_rms_tracking_error = ...
            indirect_case.rms_tracking_error;
        case_validation.indirect_final_prediction_error = ...
            indirect_case.final_prediction_error;
        case_validation.information_effective_rank = ...
            indirect_case.information_effective_rank;
        case_validation.minimum_regularized_singular_value = ...
            minimum_regularized_singular_value;
        validation.cases(ic) = case_validation;
    end
end

